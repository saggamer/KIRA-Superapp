"""Image annotation decoding and controlled spatial supervision.

MagicBrush RGBA assets are source photographs with transparent edit holes.
Their RGB luminance must never be treated as an edit mask.
"""
from pathlib import Path
import hashlib
import random
import numpy as np
from PIL import Image, ImageDraw

def annotation_mask(image, size=(512,512)):
    if 'A' in image.getbands() and image.getchannel('A').getextrema()[0] < 255:
        mask=Image.fromarray(255-np.asarray(image.getchannel('A')),mode='L')
        encoding='inverse_alpha'
    else:
        gray=np.asarray(image.convert('L'))
        if not np.isin(gray,[0,255]).all():
            raise ValueError('Opaque photographic annotation is not a binary mask')
        mask=image.convert('L');encoding='binary_white'
    mask=mask.resize(size,Image.Resampling.NEAREST)
    fraction=float((np.asarray(mask)>127).mean())
    if not 0.0001 < fraction < .95:
        raise ValueError('Public mask has no usable localized region')
    return mask,{'encoding':encoding,'fraction':fraction}

def pixel_identity(image):
    image=image.convert('RGB')
    return hashlib.sha256(str(image.size).encode()+image.tobytes()).hexdigest()

def spatial_scene(seed, group):
    """Four exact instructions on the SAME image prevent a fixed-center answer.

    Procedural shapes supplement real photographs; they are not generated by
    Horizon or evidence of photorealistic editing capability.
    """
    rng=random.Random(seed);source=Image.new('RGB',(512,512),'white');draw=ImageDraw.Draw(source)
    shape=rng.choice(['circle','square']);color=rng.choice(['red','blue','orange','purple'])
    y=rng.randint(265,355);radius=rng.randint(34,55)
    centers=[(rng.randint(95,175),y),(rng.randint(335,420),y+rng.randint(-24,24))]
    boxes=[]
    def paint(canvas,box,fill):
        drawing=ImageDraw.Draw(canvas)
        (drawing.ellipse if shape=='circle' else drawing.rectangle)(box,fill=fill)
    for x,cy in centers:
        box=(x-radius,cy-radius,x+radius,cy+radius);boxes.append(box);paint(source,box,color)
    rows=[]
    for side,index in [('left',0),('right',1)]:
        box=boxes[index];target=source.copy();mask=Image.new('L',source.size)
        paint(target,box,'green');paint(mask,box,255)
        rows.append({'group_id':group,'record_id':group+'-recolor-'+side,'prompt':f'Make only the {side} {color} {shape} green. Keep everything else unchanged.','category':'controlled_recolor','source':source.copy(),'target':target,'mask':mask})
        x,cy=centers[index];box=(x-18,cy-radius-65,x+18,cy-radius-29)
        target=source.copy();mask=Image.new('L',source.size)
        ImageDraw.Draw(target).ellipse(box,fill='black');ImageDraw.Draw(mask).ellipse(box,fill=255)
        rows.append({'group_id':group,'record_id':group+'-add-'+side,'prompt':f'Add a small black dot directly above the {side} {color} {shape}. Keep everything else unchanged.','category':'controlled_addition','source':source.copy(),'target':target,'mask':mask})
    return rows

def mask_metrics(prediction, reference, threshold=.5):
    probability=np.asarray(prediction,dtype='float32');truth=np.asarray(reference,dtype='float32')
    if probability.shape!=truth.shape or probability.ndim!=2 or not np.isfinite(probability).all():
        raise ValueError('Aligned finite 2D probability and reference maps required')
    positive=probability>threshold;gold=truth>.5
    intersection=int((positive&gold).sum());union=int((positive|gold).sum())
    point=np.unravel_index(int(probability.argmax()),probability.shape)
    return {'iou':intersection/union if union else 1.,'pointing_success':bool(gold[point]) if gold.any() else None,
            'predicted_fraction':float(positive.mean()),'reference_fraction':float(gold.mean()),
            'empty_prediction':not bool(positive.any())}
